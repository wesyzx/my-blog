"""Build the iPhone Photos album publishing Shortcut.

The public build prompts for a short-lived upload token at runtime. Personal
builds may inline it, but are written only below
`/private/tmp/personal-gallery-shortcuts` with restrictive permissions.
"""

import argparse
import copy
import getpass
import os
import pathlib
import plistlib
import uuid

PERSONAL_DIRECTORY = pathlib.Path('/private/tmp/personal-gallery-shortcuts')
ALBUM_ENDPOINT = 'https://img.215320.xyz/internal/gallery/albums'
MEDIA_CONFIG = {
    'photo': {
        'slug': '相册同步到博客',
        'noun': '照片',
        'upload_path': 'photos',
        'content_type': 'image/jpeg',
        'converted_output_name': 'Converted Image',
    },
    'video': {
        'slug': '视频同步到博客',
        'noun': '视频',
        'upload_path': 'videos',
        'content_type': 'video/quicktime',
        'converted_output_name': 'Encoded Media',
    },
}


def uid():
    return str(uuid.uuid4()).upper()


def attachment(ref):
    return {'WFSerializationType': 'WFTextTokenAttachment', 'Value': ref}


def variable_input(ref):
    return {'Type': 'Variable', 'Variable': attachment(ref)}


def output(identifier, name):
    return {'Type': 'ActionOutput', 'OutputUUID': identifier, 'OutputName': name}


def text(value='', ref=None):
    state = {'string': value + ('\ufffc' if ref else '')}
    if ref:
        state['attachmentsByRange'] = {'{%d, 1}' % len(value): ref}
    return {'WFSerializationType': 'WFTextTokenString', 'Value': state}


def composed_text(*parts):
    value = ''
    attachments = {}
    for part in parts:
        if isinstance(part, str):
            value += part
        else:
            attachments['{%d, 1}' % len(value)] = part
            value += '\ufffc'
    return {'WFSerializationType': 'WFTextTokenString', 'Value': {
        'string': value,
        'attachmentsByRange': attachments,
    }}


def dictionary(items):
    return {
        'WFSerializationType': 'WFDictionaryFieldValue',
        'Value': {
            'WFDictionaryFieldValueItems': [
                {'WFItemType': kind, 'WFKey': text(key), 'WFValue': value}
                for key, value, kind in items
            ],
        },
    }


def empty_dictionary():
    return dictionary([])


def build(personal_token=None, workflow_name='相册同步到博客', media='photo'):
    if media not in MEDIA_CONFIG:
        raise ValueError('media must be "photo" or "video"')
    config = MEDIA_CONFIG[media]
    noun = config['noun']
    actions = []

    def action(identifier_name, **params):
        identifier = uid()
        params['UUID'] = identifier
        actions.append({
            'WFWorkflowActionIdentifier': 'is.workflow.actions.' + identifier_name,
            'WFWorkflowActionParameters': params,
        })
        return identifier

    action('comment', WFCommentActionText=(
        f'打开照片选择器，手动选择要公开的{noun}并直接上传选中的项目，'
        '创建博客相册并触发网站部署。\n'
        f'可以在选择器底部打开“相簿”，先进入指定相簿再挑选{noun}。'
        '本指令不会创建或修改 iCloud 共享相簿。'))
    action('comment', WFCommentActionText=(
        'Shortcuts generated by Shortcuts Playground. May contain mistakes. '
        'Always check the shortcut\'s actions first.\n\n'
        f'This shortcut opens the Photos picker, uploads the selected {noun} to the blog, '
        'then publishes the resulting gallery.\n\n'
        '相册在发布前保持私密；只有最后发布成功，网站才会读取它。'
        + ('图片会在手机上转换为 JPEG，兼容 Cloudflare Images 普通方案。'
           if media == 'photo'
           else '视频保留 iPhone 原生 QuickTime 格式，并由博客直接内嵌播放。')
        +
        '上传令牌只用于本次操作；公开版每次运行时输入，个人版保存在本机私有快捷指令中。'))

    picker_parameters = {'WFSelectMultiplePhotos': True}
    if media == 'video':
        picker_parameters['WFPhotoPickerTypes'] = 'Videos'
    selected_photos_id = action('selectphoto', **picker_parameters)
    selected_items = attachment(output(selected_photos_id, 'Photos'))
    selected_count_id = action(
        'count',
        WFCountType='Items',
        WFInput=selected_items,
        Input=selected_items,
    )
    no_selection_group = uid()
    action(
        'conditional',
        GroupingIdentifier=no_selection_group,
        WFControlFlowMode=0,
        WFCondition=2,
        WFNumberValue=0.0,
        WFInput=variable_input(output(selected_count_id, 'Count')),
    )
    action('conditional', GroupingIdentifier=no_selection_group, WFControlFlowMode=1)
    action(
        'showresult',
        WFInput=text(f'没有选择任何{noun}。请返回照片选择器，选择至少一个{noun}后再运行。'),
    )
    action('exit')
    action('conditional', GroupingIdentifier=no_selection_group, WFControlFlowMode=2)

    current_date_id = action('date', WFDateActionMode='Current Date')
    formatted_date_id = action(
        'format.date',
        WFDate=text('', output(current_date_id, 'Date')),
        WFDateFormatStyle='Custom',
        WFDateFormat='yyyy-MM-dd',
    )
    gallery_date_id = action(
        'ask',
        CustomOutputName='Gallery Date',
        WFAskActionPrompt=(
            f'{noun}日期（YYYY-MM-DD，例如 2016-03-12；默认今天）'
        ),
        WFAskActionDefaultAnswer=text('', output(formatted_date_id, 'Formatted Date')),
        WFInputType='Text',
    )
    album_title_id = action(
        'ask',
        CustomOutputName='Gallery Title',
        WFAskActionPrompt='输入博客相册标题（例如：十月散步）',
        WFInputType='Text',
    )
    album_slug_id = action(
        'ask',
        CustomOutputName='Gallery Link',
        WFAskActionPrompt='相册链接短名（英文，例如 tuotuo-first-month；留空自动命名）',
        WFInputType='Text',
    )
    token_id = action(
        'ask',
        CustomOutputName='Upload Token',
        WFAskActionPrompt='输入博客相册上传令牌（仅本次使用）',
        WFInputType='Text',
    )

    action('comment', WFCommentActionText='先创建一条尚未公开的相册记录，取得服务端相册编号。')
    create_headers = dictionary([
        ('Authorization', text('Bearer ', output(token_id, 'Upload Token')), 0),
        ('Content-Type', text('application/json'), 0),
    ])
    create_body = dictionary([
        ('title', text('', output(album_title_id, 'Gallery Title')), 0),
        ('slug', text('', output(album_slug_id, 'Gallery Link')), 0),
        ('date', text('', output(gallery_date_id, 'Gallery Date')), 0),
    ])
    create_id = action(
        'downloadurl',
        WFURL=ALBUM_ENDPOINT,
        WFHTTPMethod='POST',
        WFHTTPBodyType='JSON',
        WFJSONValues=create_body,
        WFHTTPHeaders=create_headers,
    )
    create_dictionary_id = action(
        'detect.dictionary',
        WFInput=attachment(output(create_id, 'Contents of URL')),
    )
    album_id = action(
        'getvalueforkey',
        WFGetDictionaryValueType='Value',
        WFDictionaryKey=text('albumId'),
        WFInput=attachment(output(create_dictionary_id, 'Dictionary')),
    )
    create_guard_group = uid()
    action(
        'conditional',
        GroupingIdentifier=create_guard_group,
        WFControlFlowMode=0,
        WFCondition=100,
        WFInput=variable_input(output(album_id, 'Dictionary Value')),
    )
    action('conditional', GroupingIdentifier=create_guard_group, WFControlFlowMode=1)
    action('showresult', WFInput=text('相册创建失败。服务端原始响应：'))
    action('showresult', WFInput=attachment(output(create_id, 'Contents of URL')))
    action('exit')
    action('conditional', GroupingIdentifier=create_guard_group, WFControlFlowMode=2)

    action('comment', WFCommentActionText=(
        '直接读取照片选择器返回的项目，避免再次扫描整个照片图库。\n'
        + (
            '逐张转换并上传刚选择并确认的照片；单张失败时整个快捷指令停止。\n'
            '- “重复”读取“选择照片”的结果。\n'
            '- “转换图像”读取“重复项目”。\n'
            '- “获取 URL 内容”以“转换后的图像”作为文件正文。'
            if media == 'photo'
            else
            '逐个转换并上传刚选择并确认的视频；单个失败时整个快捷指令停止。\n'
            '- “重复”读取“选择照片”的结果。\n'
            '- “编码媒体”读取“重复项目”，生成可上传的视频文件。\n'
            '- “获取 URL 内容”以“编码后的媒体”作为文件正文。'
        )))
    group = uid()
    action(
        'repeat.each',
        GroupingIdentifier=group,
        WFControlFlowMode=0,
        WFInput=attachment(output(selected_photos_id, 'Photos')),
    )
    converted_id = None
    if media == 'photo':
        converted_id = action(
            'image.convert',
            WFInput=attachment({'Type': 'Variable', 'VariableName': 'Repeat Item'}),
            WFImageFormat='JPEG',
            WFImageCompressionQuality=0.9,
            WFImagePreserveMetadata=False,
        )
    else:
        converted_id = action(
            'encodemedia',
            WFMedia=attachment({'Type': 'Variable', 'VariableName': 'Repeat Item'}),
            WFMediaAudioOnly=False,
            WFMediaSize='Passthrough',
            WFMediaSpeed='Normal',
        )
    upload_headers = dictionary([
        ('Authorization', text('Bearer ', output(token_id, 'Upload Token')), 0),
        ('Content-Type', text(config['content_type']), 0),
    ])
    upload_body = output(converted_id, config['converted_output_name'])
    upload_id = action(
        'downloadurl',
        WFURL=composed_text(
            ALBUM_ENDPOINT + '/',
            output(album_id, 'Dictionary Value'),
            '/' + config['upload_path'],
        ),
        WFHTTPMethod='POST',
        WFHTTPBodyType='File',
        WFRequestVariable=attachment(upload_body),
        WFFormValues=empty_dictionary(),
        WFHTTPHeaders=upload_headers,
    )
    upload_dictionary_id = action(
        'detect.dictionary',
        WFInput=attachment(output(upload_id, 'Contents of URL')),
    )
    upload_ok_id = action(
        'getvalueforkey',
        WFGetDictionaryValueType='Value',
        WFDictionaryKey=text('ok'),
        WFInput=attachment(output(upload_dictionary_id, 'Dictionary')),
    )
    upload_guard_group = uid()
    action(
        'conditional',
        GroupingIdentifier=upload_guard_group,
        WFControlFlowMode=0,
        WFCondition=100,
        WFInput=variable_input(output(upload_ok_id, 'Dictionary Value')),
    )
    action('conditional', GroupingIdentifier=upload_guard_group, WFControlFlowMode=1)
    action('showresult', WFInput=text(f'{noun}上传失败。服务端原始响应：'))
    action('showresult', WFInput=attachment(output(upload_id, 'Contents of URL')))
    action('exit')
    action('conditional', GroupingIdentifier=upload_guard_group, WFControlFlowMode=2)
    action('repeat.each', GroupingIdentifier=group, WFControlFlowMode=2)

    action('comment', WFCommentActionText=(
        f'全部{noun}上传后才发布；发布动作会让相册公开，并触发 EdgeOne 构建。'
        '如果部署触发失败，服务端会撤回公开状态。'))
    publish_id = action(
        'downloadurl',
        WFURL=composed_text(
            ALBUM_ENDPOINT + '/',
            output(album_id, 'Dictionary Value'),
            '/publish',
        ),
        WFHTTPMethod='POST',
        WFHTTPBodyType='JSON',
        WFJSONValues=empty_dictionary(),
        WFHTTPHeaders=dictionary([
            ('Authorization', text('Bearer ', output(token_id, 'Upload Token')), 0),
            ('Content-Type', text('application/json'), 0),
        ]),
    )
    action('previewdocument', WFInput=attachment(output(publish_id, 'Contents of URL')))
    publish_dictionary_id = action(
        'detect.dictionary',
        WFInput=attachment(output(publish_id, 'Contents of URL')),
    )
    gallery_url_id = action(
        'getvalueforkey',
        WFGetDictionaryValueType='Value',
        WFDictionaryKey=text('url'),
        WFInput=attachment(output(publish_dictionary_id, 'Dictionary')),
    )
    action('openurl', WFInput=attachment(output(gallery_url_id, 'Dictionary Value')))

    workflow = {
        'WFQuickActionSurfaces': [],
        'WFWorkflowActions': actions,
        'WFWorkflowClientVersion': '4711',
        'WFWorkflowHasOutputFallback': False,
        'WFWorkflowHasShortcutInputVariables': False,
        'WFWorkflowIcon': {
            'WFWorkflowIconGlyphNumber': 61459,
            'WFWorkflowIconStartColor': 463140863,
        },
        'WFWorkflowImportQuestions': [],
        'WFWorkflowInputContentItemClasses': [],
        'WFWorkflowMinimumClientVersion': 900,
        'WFWorkflowMinimumClientVersionString': '900',
        'WFWorkflowOutputContentItemClasses': [],
        'WFWorkflowTypes': ['WFWorkflowTypeShowInSearch'],
        'WFWorkflowName': workflow_name,
    }
    if personal_token:
        token_ids = set()
        for entry in workflow['WFWorkflowActions']:
            params = entry['WFWorkflowActionParameters']
            if (entry['WFWorkflowActionIdentifier'] == 'is.workflow.actions.ask'
                    and '上传令牌' in params.get('WFAskActionPrompt', '')):
                token_ids.add(params['UUID'])
                entry['WFWorkflowActionIdentifier'] = 'is.workflow.actions.gettext'
                entry['WFWorkflowActionParameters'] = {
                    'UUID': params['UUID'],
                    'CustomOutputName': params.get('CustomOutputName', 'Upload Token'),
                    'WFTextActionText': text(personal_token),
                }
            if 'WFCommentActionText' in params:
                params['WFCommentActionText'] = params['WFCommentActionText'].replace(
                    '公开版每次运行时输入，个人版保存在本机私有快捷指令中。',
                    '个人版已配置上传令牌；请勿分享或导出给他人。',
                )

        def update_references(value):
            if isinstance(value, dict):
                if value.get('OutputUUID') in token_ids:
                    value['OutputName'] = 'Upload Token'
                for child in value.values():
                    update_references(child)
            elif isinstance(value, list):
                for child in value:
                    update_references(child)

        update_references(workflow)
    return workflow


def save(workflow, output_dir, personal=False, media='photo'):
    slug = MEDIA_CONFIG[media]['slug']
    directory = pathlib.Path(output_dir).resolve()
    if personal:
        try:
            directory.relative_to(PERSONAL_DIRECTORY)
        except ValueError as error:
            raise ValueError(
                'Personal builds must stay below /private/tmp/personal-gallery-shortcuts'
            ) from error
        directory.mkdir(mode=0o700, parents=True, exist_ok=True)
        directory.chmod(0o700)
        target = directory / (f'{slug}-{uid()}-unsigned.shortcut')
        mode = 'xb'
    else:
        directory.mkdir(mode=0o700, parents=True, exist_ok=True)
        target = directory / f'{slug}-unsigned.shortcut'
        mode = 'wb'
    with target.open(mode) as destination:
        os.chmod(target, 0o600)
        plistlib.dump(workflow, destination, fmt=plistlib.FMT_BINARY)
    return target


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--personal', action='store_true', help='Inline an upload token in a private build')
    parser.add_argument('--output-dir', help='Output directory; personal builds are restricted to /private/tmp')
    parser.add_argument('--media', choices=sorted(MEDIA_CONFIG), default='photo',
                        help='Publish static photos or native videos')
    parser.add_argument('--name', help='Shortcut name shown in the Shortcuts app')
    options = parser.parse_args()

    token = None
    if options.personal:
        token = (os.environ.get('GALLERY_UPLOAD_TOKEN')
                 or getpass.getpass('博客相册上传令牌（只写入本机私有快捷指令）：')).strip()
        if len(token) < 24:
            parser.error('个人版令牌至少需要 24 个字符')
        output_dir = options.output_dir or str(PERSONAL_DIRECTORY)
    else:
        output_dir = options.output_dir or '/private/tmp/gallery-shortcut-build'

    workflow_name = options.name or MEDIA_CONFIG[options.media]['slug']
    target = save(
        build(personal_token=token, workflow_name=workflow_name, media=options.media),
        output_dir,
        personal=options.personal,
        media=options.media,
    )
    print(target)


if __name__ == '__main__':
    main()
